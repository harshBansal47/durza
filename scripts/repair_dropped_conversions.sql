"""One-off repair for a database where the discarded migration c21f9807176e ran.

That migration was never committed and it was wrong: it dropped the
`conversions` table (Alembic read the new `CouponSource` model as a rename of
the existing `Conversion` model) and left the `conversion_status` enum type
orphaned behind it. Anyone who applied it has a half-applied schema.

This script restores the database to exactly the `d7a2b5c8e913` revision so the
corrected migration can be applied from a clean base. It is idempotent, so it is
safe to run twice, and it is a no-op on a database that was never affected.

    psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f scripts/repair_dropped_conversions.sql

After running it:

    alembic stamp d7a2b5c8e913
    alembic upgrade head

`ON_ERROR_STOP=1` matters: inside an aborted transaction every later statement
fails, and without it psql happily prints `CREATE TABLE` for a statement that
never ran — which is how a repair script can appear to succeed while leaving
the schema unchanged.

`conversions` is recreated empty. Rows dropped by the bad migration cannot be
recovered by any script — if the table held real transactions, restore from a
`pg_dump` taken before c21f9807176e was applied instead of running this.
"""

BEGIN;

-- The half-applied state: a table built from the wrong model, plus an enum
-- type that outlived it. Both are removed wholesale so the corrected
-- migration creates them properly.
DROP TABLE IF EXISTS coupon_sources CASCADE;
DROP TYPE IF EXISTS coupon_source_status;

-- `conversion_status` also survives as an orphan — `drop_table` removes the
-- column that used the type but leaves the type itself, and nothing tracked it.
-- So the pre-existing table has to go too, or `CREATE TYPE` below fails on a
-- type that is already there.
DROP TABLE IF EXISTS conversions CASCADE;
DROP TYPE IF EXISTS conversion_status;

-- Recreate `conversions` exactly as revision a1c9e3f7b251 defined it.
CREATE TYPE conversion_status AS ENUM ('pending', 'approved', 'declined', 'deleted');

CREATE TABLE conversions (
    id                UUID                     NOT NULL,
    network           VARCHAR(20)              NOT NULL,
    network_txn_id    VARCHAR(64)              NOT NULL,
    clickref          VARCHAR(64),
    click_id          UUID,
    store_id          UUID,
    status            conversion_status        NOT NULL,
    sale_amount       NUMERIC(12, 2),
    commission_amount NUMERIC(12, 2),
    currency          VARCHAR(3),
    transaction_at    TIMESTAMP WITH TIME ZONE,
    click_at          TIMESTAMP WITH TIME ZONE,
    validated_at      TIMESTAMP WITH TIME ZONE,
    decline_reason    VARCHAR(200),
    created_at        TIMESTAMP WITH TIME ZONE  DEFAULT now() NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE  DEFAULT now() NOT NULL,
    CONSTRAINT conversions_pkey PRIMARY KEY (id),
    CONSTRAINT conversions_click_id_fkey FOREIGN KEY (click_id)
        REFERENCES click_events (id) ON DELETE SET NULL,
    CONSTRAINT conversions_store_id_fkey FOREIGN KEY (store_id)
        REFERENCES stores (id) ON DELETE SET NULL
);

-- Revision a1c9e3f7b251 declared three unique indexes; the autogenerated
-- counterpart produced four by dropping the implicit one on network_txn_id.
-- The unique index on (network, network_txn_id) is the one that enforces
-- "a network transaction is never counted twice", so it is kept as the
-- primary constraint and the redundant single-column index is not recreated.
CREATE UNIQUE INDEX ix_conversions_network_txn ON conversions (network, network_txn_id);
CREATE INDEX ix_conversions_store_txn ON conversions (store_id, transaction_at);
CREATE INDEX ix_conversions_clickref ON conversions (clickref);
CREATE INDEX ix_conversions_click_id ON conversions (click_id);

COMMIT;
